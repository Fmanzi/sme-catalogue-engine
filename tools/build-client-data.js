/* Builds the only public data bundle consumed by the static storefront. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const client = process.argv[2] || 'meridian';
const clientDir = path.join(root, 'clients', client);
function read(name) { return JSON.parse(fs.readFileSync(path.join(clientDir, name), 'utf8')); }
const business = read('business.json');
const catalogue = read('catalogue.json');

/* Strip internal cost data before building public bundle */
catalogue.products = catalogue.products.map(p => {
  const { _source, _row, ...clean } = p;
  return clean;
});

const payload = { business, catalogue };
const destination = path.join(root, 'assets/js/client-data.js');
fs.writeFileSync(destination, `/* Generated by tools/build-client-data.js. Do not edit. */\nwindow.CatalogueData = ${JSON.stringify(payload)};\n`);
console.log(`Built public data bundle for ${client}: ${path.relative(root, destination)}`);

/* ---------- theme.css ---------- */

function normalizeHex(hex) {
  let h = String(hex || '').trim();
  if (!h) return '#b8874a';
  if (h[0] !== '#') h = '#' + h;
  if (/^#[0-9a-fA-F]{3}$/.test(h)) h = '#' + h[1] + h[1] + h[2] + h[2] + h[3] + h[3];
  return /^#[0-9a-fA-F]{6}$/.test(h) ? h.toLowerCase() : '#b8874a';
}
function hexToRgb(hex) {
  const h = normalizeHex(hex);
  return [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)];
}
function mix(c1, c2, t) {
  const a = hexToRgb(c1);
  const b = hexToRgb(c2);
  return '#' + a.map((v, i) => Math.round(v + (b[i] - v) * t).toString(16).padStart(2, '0')).join('');
}
function lighten(hex, pct) { return mix(hex, '#ffffff', Math.min(1, pct / 100)); }
function darken(hex, pct) { return mix(hex, '#000000', Math.min(1, pct / 100)); }

const brand = business.brand || {};
const gold = normalizeHex(brand.primary || '#b8874a');
const ink = normalizeHex(brand.secondary || '#141519');
const themeCss = `/* Generated by tools/build-client-data.js. Do not edit. */
:root {
  --gold: ${gold};
  --gold-dark: ${darken(gold, 22)};
  --gold-light: ${lighten(gold, 26)};
  --ink: ${ink};
  --ink-soft: ${lighten(ink, 8)};
}
`;
fs.writeFileSync(path.join(root, 'assets/css/theme.css'), themeCss);
console.log(`Built theme.css from business.brand for ${client}: assets/css/theme.css`);
