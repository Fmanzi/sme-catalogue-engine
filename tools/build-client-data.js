/* Builds the only public data bundle consumed by the static storefront. */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const client = process.argv[2] || 'meridian';
const clientDir = path.join(root, 'clients', client);
function read(name) { return JSON.parse(fs.readFileSync(path.join(clientDir, name), 'utf8')); }
const business = read('business.json');
const catalogue = read('catalogue.json');
const payload = { business, catalogue };
const destination = path.join(root, 'assets/js/client-data.js');
fs.writeFileSync(destination, `/* Generated by tools/build-client-data.js. Do not edit. */\nwindow.CatalogueData = ${JSON.stringify(payload)};\n`);
console.log(`Built public data bundle for ${client}: ${path.relative(root, destination)}`);
